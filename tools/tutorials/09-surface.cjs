// 09 — scene: strands immobilized on a surface, a strand handed from one anchor to the next.
const { run } = require('./lib.cjs');
run('09-surface', async t => {
  await t.view(2.4, 115, 60);
  await t.move(640, 360, 1);
  await t.title('9 · Scene: operations on a surface', 'immobilized strands on the stock surface block');
  await t.cap('Library → Shapes → surface block', 400);
  await t.click('#libraryBody .side-name:text-is("Shapes")', 600);
  await t.click('#libraryBody .side-name:text-is("surface block")', 900);
  await t.wdrag([await t.selCenter(), [115, 117]]);
  await t.click('#libraryBody .side-name:text-is("Shapes")', 300);
  await t.select([]);
  await t.cap('An anchor strand standing on it, drawn 5′ at the surface', 400);
  await t.swatch(0);
  await t.click('[data-tool="path"]', 300);
  await t.wdrag([[60, 110], [60, 10]]);
  await t.cap('Its top is the docking domain s*', 400);
  await t.click('[data-tool="segment"]', 200);
  await t.wdrag([[60, 50], [60, 10]]);
  await t.fill('Label', 's*');
  await t.cap('A filled circle marks the attachment point', 400);
  await t.select([]);
  await t.click('[data-tool="ellipse"]', 300);
  await t.wdrag([[54, 104], [66, 116]]);
  await t.check('Fill', 400);
  await t.tool('v');
  await t.cap('Ctrl+drag both to make a second anchor', 400);
  await t.at(60, 80, 200);
  await t.pg.keyboard.down('Shift'); await t.at(54, 110, 200); await t.pg.keyboard.up('Shift');
  await t.wdrag([[60, 80], [160, 80]], 18, ['Control']);
  await t.select([]);
  await t.cap('A signal strand docks on the first anchor through s', 400);
  await t.swatch(1);
  await t.click('[data-tool="path"]', 300);
  await t.wdrag([[70, 0], [70, 50]]);
  await t.tool('v');
  await t.fill('Label', 's');
  await t.at(70, 30, 200);
  await t.pg.keyboard.down('Shift'); await t.at(60, 30, 200); await t.pg.keyboard.up('Shift');
  await t.ctx(60, 30);
  await t.ctxItem('Pair with Base Pairs', 1000);
  await t.select([]);
  await t.cap('Frame the step with a card, then Ctrl+drag the card for the next step', 400);
  await t.zoomTo(1.25, 270, 60);
  await t.click('[data-tool="card"]', 300);
  await t.wdrag([[-20, -40], [250, 150]]);
  await t.tool('v');
  await t.fill('Title', 'docked');
  await t.wdrag([[115, -40], [415, -40]], 18, ['Control']);
  await t.select([]);
  await t.at(415, -40, 300);
  await t.fill('Title', 'handed over');
  await t.select([]);
  await t.zoomTo(2.4, 420, 60);
  await t.cap('In step 2, right-click the signal → Remove Link, and move it to the second anchor', 400);
  await t.ctx(370, 30);
  await t.ctxItem('Remove Link', 600);
  await t.at(370, 30, 200);
  await t.wdrag([[370, 30], [470, 30]]);
  await t.at(470, 30, 200);
  await t.pg.keyboard.down('Shift'); await t.at(460, 30, 200); await t.pg.keyboard.up('Shift');
  await t.ctx(460, 30);
  await t.ctxItem('Pair with Base Pairs', 1000);
  await t.select([]);
  await t.zoomTo(1.25, 270, 60);
  await t.cap('Connect the steps', 400);
  await t.tool('a');
  await t.wdrag([[240, 40], [300, 40]], 18);
  await t.fill('Label', 'relay');
  await t.tool('v');
  await t.select([]);
  await t.cap('Select all → Draw As → DNA molecule', 400);
  await t.key('Control+a', 300);
  await t.ctx(60, 80);
  await t.hover('.ctx-menu button:has-text("Draw As")', 500);
  await t.click('.ctx-menu button:has-text("DNA molecule")', 1500);
  await t.select([]);
  await t.zoomTo(1.45, 265, 55);
  await t.cap('Anchored strands, a hand-over, two steps — all still editable', 2600);
  await t.cap('', 300);
}, { hide: ['notes'] });
