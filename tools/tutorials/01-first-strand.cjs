// 01 — a first strand: draw, end caps, smooth curve, LaTeX label, label style.
const { run } = require('./lib.cjs');
run('01-first-strand', async t => {
  await t.view(3, 80, 40);
  await t.move(640, 360, 1);
  await t.title('1 · A first strand', 'draw a line, give it ends, a curve and a typeset label');
  await t.cap('The Strand tool (L) draws along the half-grid; turns become corners', 600);
  await t.click('[data-tool="path"]', 300);
  await t.wdrag([[0, 20], [60, 20], [60, 50], [140, 50]], 16);
  await t.cap('Pick a colour while it is selected', 400);
  await t.swatch(6);
  await t.tool('v');
  await t.at(40, 20, 400);
  await t.cap('End cap: a barb marks the 3′ end', 400);
  await t.pick('End cap', 'barb');
  await t.cap('…or a harpoon, a half-arrow often used for DNA', 400);
  await t.pick('End cap', 'harpoon');
  await t.cap('Smooth curve rounds the path through its points', 400);
  await t.check('Smooth curve through the points', 1200);
  await t.cap('Label it. Anything between $…$ is typeset by KaTeX', 400);
  await t.fill('Label', 'primer $\\alpha_1$', 70);
  await t.at(30, 20, 900);
  await t.cap('Labels have their own size, weight and colour', 400);
  await t.reveal(`${t.F('Label size')} input`);
  await t.field(`${t.F('Label size')} input`, '16');
  await t.pick('Label weight', '400', 900);
  await t.cap('Drag a label to move it', 400);
  const [lx, ly] = await t.pg.evaluate(() => { const r = document.querySelector('[data-labelfor]').getBoundingClientRect(); return [r.x + r.width / 2, r.y + r.height / 2]; });
  await t.drag([[lx, ly], [lx - 90, ly - 75]]);
  await t.cap('Edit line (E): drag a vertex, click the line to add one', 400);
  await t.tool('e');
  await t.at(30, 20, 300);
  await t.wdrag([[60, 50], [60, 70]]);
  await t.tool('v');
  await t.deselect();
  await t.cap('Copy with Ctrl+drag; the copy keeps caps, curve and label', 400);
  await t.wdrag([[30, 20], [30, 100]], 16, ['Control']);
  await t.deselect();
  await t.zoomTo(2.6, 80, 55);
  await t.cap('A strand with caps, a curve and a typeset label — every part still editable', 2200);
  await t.cap('', 300);
});
