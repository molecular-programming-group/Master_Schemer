// 02 — primer on a template: domains by name, complements, base-pair links, DNA look.
const { run } = require('./lib.cjs');
run('02-primer-template', async t => {
  await t.view(3.2, 80, 60);
  await t.move(640, 360, 1);
  await t.title('2 · Primer and template', 'domains, complements, base pairs');
  await t.cap('Two strands, drawn in opposite directions: a template 5′→3′, a primer 5′←3′', 500);
  await t.click('[data-tool="path"]', 300);
  await t.swatch(0);
  await t.wdrag([[0, 40], [160, 40]]);
  await t.wdrag([[150, 30], [90, 30]]);
  await t.cap('The Domain tool (S) marks a span of a strand: drag along it', 400);
  await t.click('[data-tool="segment"]', 300);
  await t.wdrag([[90, 40], [150, 40]]);
  await t.cap('Name it. A trailing * means complement: p* pairs with p', 400);
  await t.fill('Label', 'p*');
  await t.click('[data-tool="segment"]', 200);
  await t.wdrag([[0, 40], [90, 40]]);
  await t.fill('Label', 'x');
  await t.tool('v');
  await t.at(120, 30, 300);
  await t.fill('Label', 'p');
  await t.deselect();
  await t.cap('Every name shows up under Domains in the sidebar', 1800);
  await t.cap('Click a domain there to select all its uses, then pick a colour', 400);
  await t.click('#domainsBody .side-name:text-is("p")', 400);
  await t.swatch(1);
  await t.cap('p turns red everywhere, and p* gets a lighter shade of it', 2000);
  await t.click('#domainsBody .side-name:text-is("x")', 400);
  await t.swatch(6);
  await t.deselect();
  await t.cap('Pair them: select the primer and the p* domain, then right-click', 400);
  await t.at(120, 30, 300);
  await t.pg.keyboard.down('Shift'); await t.at(120, 40, 300); await t.pg.keyboard.up('Shift');
  await t.ctx(120, 40);
  await t.ctxItem('Pair with Base Pairs', 1200);
  await t.cap('A base-pair link: one rung per base, counted from the DNA grid', 1800);
  await t.cap('Style → Fill shades the duplex instead', 400);
  await t.pick('Style', 'fill', 1400);
  await t.pick('Style', 'bases', 900);
  await t.deselect();
  await t.cap('Step 2: Ctrl+drag a copy of the whole scheme', 400);
  await t.wdrag([[-12, 18], [165, 50]]);
  await t.wdrag([[40, 40], [40, 120]], 16, ['Control']);
  await t.deselect();
  await t.cap('Drag the primer’s 3′ end to extend it along the template', 400);
  await t.at(120, 110, 300);
  await t.wdrag([[90, 110], [10, 110]]);
  await t.cap('Mark the new part as x*: it picks up x’s colour, lightened', 400);
  await t.click('[data-tool="segment"]', 200);
  await t.wdrag([[88, 110], [10, 110]]);
  await t.fill('Label', 'x*');
  await t.tool('v');
  await t.at(75, 110, 200);
  await t.pg.keyboard.down('Shift'); await t.at(22, 120, 300); await t.pg.keyboard.up('Shift');
  await t.ctx(22, 120);
  await t.ctxItem('Pair with Base Pairs', 1200);
  await t.deselect();
  await t.zoomTo(2.4, 80, 75);
  await t.cap('Select all and Draw As → DNA molecule for a space-filling look', 400);
  await t.key('Control+a', 300);
  await t.ctx(30, 40);
  await t.hover('.ctx-menu button:has-text("Draw As")', 500);
  await t.click('.ctx-menu button:has-text("DNA molecule")', 1800);
  await t.deselect();
  await t.wait(1500);
  await t.cap('Same scheme, same domains and colours, now as a double helix', 2500);
  await t.cap('', 300);
}, { hide: ['library', 'notes'] });
