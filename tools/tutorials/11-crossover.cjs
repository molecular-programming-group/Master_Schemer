// 11 — scene: a double-crossover (DX) tile — two helices, strands that switch helices at a Holliday junction.
const { run } = require('./lib.cjs');
const pair = async (t, a, b) => {
  await t.at(...a, 200);
  await t.pg.keyboard.down('Shift'); await t.at(...b, 200); await t.pg.keyboard.up('Shift');
  await t.ctx(...b, 600);
  await t.ctxItem('Pair with Base Pairs', 700);
};
const strand = async (t, color, pts) => {
  await t.select([]); await t.swatch(color);
  await t.click('[data-tool="path"]', 200);
  await t.wdrag(pts, 12);
};
const domain = async (t, from, to) => { await t.click('[data-tool="segment"]', 150); await t.wdrag([from, to], 10); };
run('11-crossover', async t => {
  await t.view(2.6, 100, 35);
  await t.move(640, 360, 1);
  await t.title('11 · Scene: a crossover tile', 'two helices joined where strands switch between them');
  await t.cap('Two helices, each starting with one long strand: helix 1 on top, helix 2 below', 400);
  await strand(t, 6, [[0, 0], [200, 0]]);
  await strand(t, 4, [[200, 70], [0, 70]]);
  await t.cap('Crossover strands run along one helix, switch, and come back along the other', 400);
  await strand(t, 2, [[200, 10], [110, 10], [110, 60], [200, 60]]);
  await strand(t, 7, [[0, 60], [100, 60], [100, 10], [0, 10]]);
  await t.tool('v');
  await t.cap('Shift + Cut splits a strand into two domains without breaking it', 400);
  await t.tool('x');
  await t.wdrag([[105, -15], [105, 4]], 12, ['Shift']);
  await t.tool('x');
  await t.wdrag([[105, 85], [105, 66]], 12, ['Shift']);
  await t.cap('Mark the paired legs of each crossover strand with the Domain tool', 400);
  await domain(t, [200, 10], [110, 10]);
  await domain(t, [110, 60], [200, 60]);
  await domain(t, [0, 60], [100, 60]);
  await domain(t, [100, 10], [0, 10]);
  await t.tool('v');
  await t.select([]);
  await t.cap('Pair each leg with the helix strand beside it', 400);
  await pair(t, [50, 0], [50, 10]);
  await pair(t, [160, 0], [160, 10]);
  await pair(t, [160, 70], [160, 60]);
  await pair(t, [50, 70], [50, 60]);
  await t.select([]);
  await t.cap('The vertical legs are the crossovers: together they form a Holliday junction', 2400);
  await t.cap('Draw As → DNA molecule shows the two helices and the strand exchange', 400);
  await t.key('Control+a', 300);
  await t.ctx(160, 0);
  await t.hover('.ctx-menu button:has-text("Draw As")', 500);
  await t.click('.ctx-menu button:has-text("DNA molecule")', 1800);
  await t.select([]);
  await t.wait(1000);
  await t.cap('Select a crossover strand to see its direction: chevrons run 5′ → 3′', 400);
  await t.at(110, 35, 1800);
  await t.select([]);
  await t.cap('Copy the tile with Ctrl+drag to tile a lattice', 400);
  await t.zoomTo(1.4, 210, 35);
  await t.key('Control+a', 300);
  await t.wdrag([[160, 0], [380, 0]], 18, ['Control']);
  await t.select([]);
  await t.cap('Strand routing with crossovers, drawn from plain strands, domains and links', 2600);
  await t.cap('', 300);
});
