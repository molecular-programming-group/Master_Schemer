// 03 — cut and ligate, shown as reaction steps on cards joined by arrows.
const { run } = require('./lib.cjs');
run('03-cut-ligate-cards', async t => {
  await t.view(2.6, 100, 55);
  await t.move(640, 360, 1);
  await t.title('3 · Cut, ligate, and steps on cards', 'Cut tool, Join Lines, cards and arrows, arrange');
  await t.cap('The Card tool (C) frames one step of a scheme', 400);
  await t.click('[data-tool="card"]', 300);
  await t.wdrag([[0, 0], [200, 100]]);
  await t.tool('v');
  await t.fill('Title', '1 · bound');
  await t.cap('Inside it: a template and a short strand bound to it', 400);
  await t.click('[data-tool="path"]', 300);
  await t.select([]);
  await t.swatch(0);
  await t.wdrag([[20, 60], [180, 60]]);
  await t.select([]);
  await t.swatch(2);
  await t.wdrag([[140, 50], [60, 50]]);
  await t.tool('v');
  await t.select([]);
  await t.zoomTo(1.25, 320, 55);
  await t.cap('Ctrl+drag the card’s border: the card is copied with its contents', 400);
  await t.wdrag([[100, 0], [340, 0]], 18, ['Control']);
  await t.select([]);
  await t.at(340, 0, 300);
  await t.fill('Title', '2 · cut');
  await t.zoomTo(2.6, 340, 55);
  await t.cap('The Cut tool (X): drag a blade across a strand. A dot shows where it lands', 400);
  await t.tool('x');
  await t.wdrag([[340, 75], [340, 55]], 18);
  await t.cap('Cut the short strand a little further along: sticky ends', 400);
  await t.tool('x');
  await t.wdrag([[360, 35], [360, 53]], 18);
  await t.tool('v');
  await t.cap('Select the right-hand pieces and nudge them apart with the arrow keys', 400);
  await t.at(390, 60, 200);
  await t.pg.keyboard.down('Shift'); await t.at(370, 50, 300); await t.pg.keyboard.up('Shift');
  await t.key('ArrowRight', 500);
  await t.select([]);
  await t.zoomTo(1.25, 320, 55);
  await t.cap('The Connect tool (A) draws an arrow from card to card', 400);
  await t.tool('a');
  await t.wdrag([[180, 20], [260, 20]], 18);
  await t.fill('Label', 'EcoRI');
  await t.tool('v');
  await t.select([]);
  await t.cap('Copy the card again for the ligation step', 400);
  await t.wdrag([[340, 0], [580, 0]], 18, ['Control']);
  await t.select([]);
  await t.at(580, 0, 300);
  await t.fill('Title', '3 · ligated');
  await t.zoomTo(2.6, 580, 55);
  await t.cap('Nudge the pieces back so their ends meet', 400);
  await t.at(650, 60, 200);
  await t.pg.keyboard.down('Shift'); await t.at(630, 50, 300); await t.pg.keyboard.up('Shift');
  await t.key('ArrowLeft', 500);
  await t.cap('Select two strands whose ends meet, right-click → Join Lines', 400);
  await t.at(540, 60, 200);
  await t.pg.keyboard.down('Shift'); await t.at(620, 60, 200); await t.pg.keyboard.up('Shift');
  await t.ctx(620, 60);
  await t.ctxItem('Join Lines', 900);
  await t.at(570, 50, 200);
  await t.pg.keyboard.down('Shift'); await t.at(612, 50, 200); await t.pg.keyboard.up('Shift');
  await t.ctx(612, 50);
  await t.ctxItem('Join Lines', 900);
  await t.cap('One strand each again: ligated', 1500);
  await t.select([]);
  await t.zoomTo(1.25, 320, 55);
  await t.tool('a');
  await t.wdrag([[420, 20], [500, 20]], 18);
  await t.fill('Label', 'ligase');
  await t.tool('v');
  await t.select([]);
  await t.cap('Arrange: drag a card out of line, select the cards, Object → Align Top', 400);
  await t.wdrag([[580, 0], [580, 40]]);
  await t.m(m => { m.state.selection = m.state.doc.elements.filter(e => e.type === 'card').map(e => ({ id: e.id })); m.changed(); });
  await t.wait(400);
  await t.menu('Object', '[role=menuitem][data-act="alignTop"]');
  await t.wait(900);
  await t.select([]);
  await t.cap('Three steps of a scheme, each strand still an editable object', 2400);
  await t.cap('', 300);
});
