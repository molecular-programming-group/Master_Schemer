// 12 — scene: a small DNA origami: a scaffold rastered over four helices, staples crossing between them.
const { run } = require('./lib.cjs');
run('12-mini-origami', async t => {
  await t.view(2.3, 100, 60);
  await t.move(640, 360, 1);
  await t.title('12 · Scene: a small DNA origami', 'a scaffold folded by staples');
  await t.cap('The scaffold snakes across four helices. Short turns: drag past the corner, then back', 400);
  await t.select([]); await t.swatch(0);
  await t.click('[data-tool="path"]', 200);
  await t.wdrag([[0, 0], [200, 0], [200, 90], [200, 40], [0, 40], [0, 130], [0, 80], [200, 80], [200, 170], [200, 120], [0, 120]], 12);
  await t.cap('Corner radius rounds the turns', 400);
  await t.field(`${t.F('Corner radius')} input[type=number]`, '10');
  await t.wait(900);
  await t.select([]);
  await t.cap('A staple: along one helix, across to the next, and back — a crossover', 400);
  await t.swatch(2);
  await t.click('[data-tool="path"]', 200);
  await t.wdrag([[90, 10], [10, 10], [10, 50], [10, 30], [90, 30]], 12);
  await t.pick('End cap', 'harpoon', 700);
  await t.tool('v');
  await t.cap('Ctrl+drag a copy, then Object → Flip Horizontal', 400);
  await t.wdrag([[50, 10], [150, 10]], 16, ['Control']);
  await t.menu('Object', '[role=menuitem][data-act="flipH"]');
  await t.wait(700);
  await t.cap('Select both staples and copy them down to the lower helices', 400);
  await t.at(50, 10, 200);
  await t.pg.keyboard.down('Shift'); await t.at(150, 10, 200); await t.pg.keyboard.up('Shift');
  await t.wdrag([[50, 10], [50, 90]], 16, ['Control']);
  await t.select([]);
  await t.cap('One more staple stitches the middle helices together', 400);
  await t.swatch(7);
  await t.click('[data-tool="path"]', 200);
  await t.wdrag([[170, 50], [110, 50], [110, 85], [110, 70], [170, 70]], 12);
  await t.pick('End cap', 'harpoon', 500);
  await t.wdrag([[30, 70], [90, 70], [90, 35], [90, 50], [30, 50]], 12);
  await t.pick('End cap', 'harpoon', 500);
  await t.tool('v');
  await t.select([]);
  await t.cap('Base ticks along the scaffold count its bases', 400);
  await t.click('#sidebar .side-name:text-is("strand 1")', 600);
  await t.pick('Base ticks', 'left', 1200);
  await t.cap('Name it in the Objects panel (double-click): a name, unlike a label, isn’t drawn', 400);
  await t.dbl('#sidebar .side-name:text-is("strand 1")', 300);
  await t.key('Control+a', 100); await t.type('scaffold', 60); await t.key('Enter', 600);
  await t.select([]);
  await t.cap('Group the staples (Ctrl+G) to move and colour them together', 400);
  await t.m(m => { m.state.selection = m.state.doc.elements.filter((e, i) => e.type === 'path' && i > 0).map(e => ({ id: e.id })); m.changed(); });
  await t.wait(500);
  await t.key('Control+g', 800);
  await t.select([]);
  await t.zoomTo(2.6, 100, 60);
  await t.cap('Scaffold and staples: the classic origami routing diagram', 2600);
  await t.cap('Every strand stays editable: give them domains, pair them, or draw them as DNA', 2600);
  await t.cap('', 300);
});
