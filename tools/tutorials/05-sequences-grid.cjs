// 05 — sequences and the DNA grid: base ticks, whole-base drawing, Draw as Sequence, resize to grid.
const { run } = require('./lib.cjs');
const G = s => `#gridMenu ${s}`;
run('05-sequences-grid', async t => {
  const box = () => t.m(m => { const xs = [], ys = [];
    for (const e of m.state.doc.elements) for (const p of e.pts || []) { xs.push(p[0]); ys.push(p[1]); }
    return [(Math.min(...xs) + Math.max(...xs)) / 2, (Math.min(...ys) + Math.max(...ys)) / 2]; });
  const frame = async s => { const [x, y] = await box(); await t.zoomTo(s, x, y); };
  await t.view(2, 120, 60);
  await t.move(640, 360, 1);
  await t.title('5 · Sequences and the DNA grid', 'base ticks, whole bases, letters, resize to fit');
  await t.cap('The Grid menu: base ticks, whole-base drawing, the scale', 400);
  await t.click('.menu-title:text-is("Grid")', 500);
  for (const s of ['[data-act="ticks"]', '[data-act="baseSnap"]', '[data-act="fitSeq"]', '[data-bpg="10"]']) await t.hover(G(s), 500);
  await t.key('Escape', 300);
  await t.cap('Zoom in: each tick on a grid line is one base (10 per square by default)', 400);
  await t.zoomTo(5, 30, 22);
  await t.wait(1400);
  await t.cap('Grid → Draw Strands in Whole Bases', 400);
  await t.menu('Grid', G('[data-act="baseSnap"]'));
  await t.cap('The Strand tool now lays whole-base legs and counts them as you draw', 400);
  await t.select([]);
  await t.swatch(6);
  await t.click('[data-tool="path"]', 300);
  await t.wdrag([[10, 10], [40, 10], [40, 30]]);
  await t.tool('v');
  await t.cap('Give it a sequence, 5′→3′, in its properties', 400);
  await t.at(40, 20, 400);
  const ta = 'textarea[placeholder^="5′→3′"]';
  await t.reveal(ta); await t.click(ta, 200);
  await t.type('ATGCATGATCGATGCATGCAGGTACCTTAGC', 45);
  await t.wait(1000);
  await t.blur();
  await t.cap('Draw as → Sequence (letters) shows the strand as its bases', 400);
  await t.pick('Draw as', 'seq', 2000);
  await t.select([]);
  await frame(6);
  await t.wait(1200);
  await t.cap('The badge at the 3′ end: the sequence is longer than the drawn strand', 2400);
  await t.cap('Grid → Resize Strands to Grid fits the length to the sequence', 400);
  await t.menu('Grid', G('[data-act="fitSeq"]'));
  await t.wait(1500);
  await t.cap('Bigger letters: fewer bases per square. Grid → 2 Bases per Square', 400);
  await t.menu('Grid', G('[data-bpg="2"]'));
  await frame(1.6);
  await t.wait(1200);
  await t.cap('Resize again: the whole shape scales, 31 nt = 15½ squares', 400);
  await t.menu('Grid', G('[data-act="fitSeq"]'));
  await frame(1.5);
  await t.wait(1500);
  await t.cap('Back to 10 bases per square, and resize', 400);
  await t.menu('Grid', G('[data-bpg="10"]'));
  await t.menu('Grid', G('[data-act="fitSeq"]'));
  await frame(1.2);
  await t.cap('Zoomed out too far to read? It draws as a plain line', 2000);
  await frame(6);
  await t.cap('View → Draw Strands overrides every strand at once', 400);
  await t.click('.menu-title:text-is("View")', 600);
  await t.hover('[data-look="dna"]', 500);
  await t.pg.mouse.click(...t.cur()); await t.wait(1800);
  await t.cap('…all as lines, or back to each strand as set', 400);
  await t.menu('View', '[data-look="line"]'); await t.wait(1300);
  await t.menu('View', '[data-look="own"]'); await t.wait(1300);
  await t.cap('Ticks and whole-base drawing keep every strand on the base grid', 2400);
  await t.cap('', 300);
});
