// 08 — links in depth: fill links between shapes, a hairpin, partial pairing, rung looks, notes with live references.
const { run } = require('./lib.cjs');
run('08-linking', async t => {
  await t.view(2.2, 90, 60);
  await t.move(640, 360, 1);
  await t.title('8 · Links in depth', 'fill links, hairpins, partial pairing, rung looks, notes that point at objects');
  await t.cap('A link fills the space between any two objects. Draw two shapes…', 400);
  await t.click('[data-tool="ellipse"]', 300);
  await t.wdrag([[0, 0], [50, 50]]);
  await t.click('[data-tool="rect"]', 300);
  await t.wdrag([[130, 0], [180, 50]]);
  await t.tool('v');
  await t.cap('…select both, right-click → Link', 400);
  await t.at(25, 2, 200);
  await t.pg.keyboard.down('Shift'); await t.at(155, 2, 200); await t.pg.keyboard.up('Shift');
  await t.ctx(155, 2);
  await t.ctxItem('Link', 900);
  await t.cap('Colour, pattern and opacity are the link’s own', 400);
  await t.swatch(6);
  await t.pick('Pattern', 'diagonal', 1200);
  await t.select([]);
  await t.cap('Move either end: the link reshapes to follow', 400);
  await t.at(155, 2, 200);
  await t.wdrag([[180, 25], [190, 75]]);
  await t.wdrag([[190, 75], [180, 25]]);
  await t.select([]);
  await t.cap('One strand can pair with itself: draw a hairpin…', 400);
  await t.click('[data-tool="path"]', 300);
  await t.wdrag([[0, 120], [160, 120], [160, 200], [160, 140], [0, 140]]);
  await t.cap('…mark the two arms as domains a and a*…', 400);
  await t.click('[data-tool="segment"]', 200);
  await t.wdrag([[20, 120], [140, 120]]);
  await t.fill('Label', 'a');
  await t.click('[data-tool="segment"]', 200);
  await t.wdrag([[140, 140], [20, 140]]);
  await t.fill('Label', 'a*');
  await t.tool('v');
  await t.cap('…and pair them: the stem of the hairpin', 400);
  await t.at(60, 120, 200);
  await t.pg.keyboard.down('Shift'); await t.at(100, 140, 200); await t.pg.keyboard.up('Shift');
  await t.ctx(100, 140);
  await t.ctxItem('Pair with Base Pairs', 1200);
  await t.cap('Partial pairing: pair only part of each domain', 400);
  const pair = '#panel label.field:has(> span:text-is("Pairs a over (%)")) input';
  await t.field(`${pair} >> nth=1`, '60');
  await t.field('#panel label.field:has(> span:text-is("Pairs a* over (%)")) input >> nth=0', '40');
  await t.wait(1200);
  await t.field(`${pair} >> nth=1`, '100');
  await t.field('#panel label.field:has(> span:text-is("Pairs a* over (%)")) input >> nth=0', '0');
  await t.cap('Base pair look: lines, dots or ticks', 400);
  await t.pick('Base pair look', 'dot', 1300);
  await t.pick('Base pair look', 'tick', 1300);
  await t.pick('Base pair look', 'line', 600);
  await t.cap('Rungs: straight across, or spread along a bend', 400);
  await t.pick('Rungs', 'spread', 1300);
  await t.pick('Rungs', 'auto', 500);
  await t.select([]);
  await t.cap('The Notes panel (status bar → Notes): drag an object from the Objects list into the text', 400);
  await t.click('#notesToggle', 500);
  await t.zoomTo(1.5, 120, 70);
  await t.dbl('#sidebarBody .side-name:text-is("strand 1")', 300);
  await t.key('Control+a', 100); await t.type('hairpin', 60); await t.key('Enter', 500);
  await t.click('#notesEditor', 300);
  await t.type('The stem of ', 40);
  const row = t.pg.locator('#sidebarBody .side-name:text-is("hairpin")').first();
  const rb = await row.boundingBox(), eb = await t.pg.locator('#notesEditor').boundingBox();
  await t.move(rb.x + 20, rb.y + rb.height / 2); await t.wait(300);
  await row.dragTo(t.pg.locator('#notesEditor'), { targetPosition: { x: Math.min(eb.width - 20, 150), y: 14 } });
  await t.move(eb.x + 150, eb.y + 14, 12);
  await t.wait(500);
  await t.click('#notesEditor', 200); await t.key('End', 100);
  await t.type(' opens when the invader binds.', 40);
  await t.cap('The reference is live: click it to select the object; renaming updates it', 400);
  await t.click('#notesEditor .chip, #notesEditor [data-ref]', 1300);
  await t.cap('', 1200);
}, { hide: ['library', 'notes'] });
